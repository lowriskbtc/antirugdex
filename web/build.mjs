/**
 * Builds site/grader.js.
 *
 *   node web/build.mjs           # minified, what gets deployed
 *   node web/build.mjs --watch   # rebuild on change, for local work
 *
 * WHY THIS IS A FILE AND NOT AN npm SCRIPT ONE-LINER — the second time this repo has paid
 * for the same lesson. `npm run sync-idl` was once an inline `node -e` whose quadruple
 * escaped UNC path collapsed under PowerShell, breaking the one step meant to stop the
 * client running against a stale IDL. The fix then was the fix now: a file has no escaping
 * layers to rot.
 *
 * The specific bug here: `--define:process.env.NODE_ENV="production"` in an npm script has
 * its quotes eaten by the shell, so esbuild received a bare IDENTIFIER named `production`
 * and substituted it into the bundle. That produced
 *
 *     if (production !== "production") return <build the real error message>
 *
 * inside @solana/errors — so every SolanaError would have thrown
 * `ReferenceError: production is not defined` INSTEAD of reporting what actually went
 * wrong. An error path that destroys the diagnostic, shipped, with the build printing only
 * a warning. esbuild did warn (`suspicious-define`); it was run through a shell that made
 * the warning look like noise.
 *
 * In here, `"production"` is a JavaScript string. There is no shell and nothing to escape.
 */
import * as esbuild from "esbuild";

const options = {
  entryPoints: {
    // outfile -> entry. Two separate bundles rather than one shared chunk: these are
    // separate pages, the grader must stay loadable with no wallet present, and a single
    // bundle would make the read-only page carry the launcher's signing code.
    "site/grader": "web/grader-entry.ts",
    "site/launcher": "web/launch-entry.ts",
  },
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  // Node globals @solana/web3.js assumes. Without this the build SUCCEEDS and the page
  // throws `Buffer is not defined` at the first RPC call.
  inject: ["web/node-shim.ts"],
  define: {
    // JSON.stringify rather than a hand-written '"production"': it cannot be got wrong,
    // and getting it wrong is what this whole comment block is about.
    "process.env.NODE_ENV": JSON.stringify("production"),
  },
  banner: {
    js: "/* GENERATED by `npm run build:web` from web/grader-entry.ts + src/grade-core.ts."
      + " Do not edit: the next build overwrites it. */",
  },
  outdir: ".",
  minify: true,
  legalComments: "none",
};

if (process.argv.includes("--watch")) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log("watching web/ and src/ — site/grader.js rebuilds on save");
} else {
  const result = await esbuild.build({ ...options, metafile: true });

  // Fail loudly on ANY warning. The define bug above shipped because a warning scrolled
  // past in a wall of build output; treating warnings as fatal is cheaper than the class of
  // bug they predict.
  if (result.warnings.length) {
    console.error(esbuild.formatMessagesSync(result.warnings, { kind: "warning" }).join("\n"));
    console.error(`\nRefusing to ship a bundle that built with ${result.warnings.length} warning(s).`);
    process.exit(1);
  }

  for (const [file, out] of Object.entries(result.metafile.outputs))
    console.log(`${file}  ${(out.bytes / 1024).toFixed(1)} kb`);
}
